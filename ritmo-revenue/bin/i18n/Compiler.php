<?php

declare(strict_types=1);

namespace Ritmo\Tools\I18n;

/**
 * Turns the entries of a .po file into the two files WordPress reads: the binary .mo of gettext
 * and the .l10n.php of WordPress 6.5+ (a PHP array of the messages; loaded first when present).
 * Untranslated and fuzzy entries are left out, so WordPress shows the English text for them.
 */
final class Compiler
{
    /** @var array<string, string> key ("context\4singular" or "singular\0plural") => translation(s) joined by "\0" */
    private array $messages = [];

    /** @var array<string, string> header name (lower case) => value */
    private array $headers = [];

    /**
     * @param list<array{context: ?string, singular: string, plural: ?string, translations: list<string>, fuzzy: bool, comments: list<string>}> $entries
     */
    public function __construct(array $entries)
    {
        foreach ($entries as $entry) {
            if ($entry['singular'] === '') {
                $this->headers = self::headers($entry['translations'][0] ?? '');
                continue;
            }
            if ($entry['fuzzy'] || $entry['translations'] === [] || in_array('', $entry['translations'], true)) {
                continue;
            }
            $key = ($entry['context'] === null ? '' : $entry['context'] . "\4") . $entry['singular'] . ($entry['plural'] === null ? '' : "\0" . $entry['plural']);
            $this->messages[$key] = implode("\0", $entry['translations']);
        }
        ksort($this->messages, SORT_STRING);
    }

    public function mo(): string
    {
        $pairs = ['' => self::headerText($this->headers)] + $this->messages;
        ksort($pairs, SORT_STRING);
        $count = count($pairs);
        $originalsAt = 28;
        $translationsAt = $originalsAt + 8 * $count;
        $dataAt = $translationsAt + 8 * $count;
        $originals = $translations = $data = '';
        foreach ($pairs as $key => $value) {
            $originals .= pack('VV', strlen((string) $key), $dataAt + strlen($data));
            $data .= $key . "\0";
        }
        foreach ($pairs as $value) {
            $translations .= pack('VV', strlen($value), $dataAt + strlen($data));
            $data .= $value . "\0";
        }

        return pack('VVVVVVV', 0x950412de, 0, $count, $originalsAt, $translationsAt, 0, $dataAt) . $originals . $translations . $data;
    }

    public function php(): string
    {
        $data = [];
        foreach (['project-id-version', 'language', 'plural-forms', 'x-domain'] as $name) {
            if (isset($this->headers[$name])) {
                $data[$name] = $this->headers[$name];
            }
        }
        $data['messages'] = $this->messages;

        return "<?php\n// Generated by bin/compile-l10n.php from the .po file; do not edit.\nreturn " . var_export($data, true) . ";\n";
    }

    public function count(): int
    {
        return count($this->messages);
    }

    /**
     * @return array<string, string>
     */
    private static function headers(string $text): array
    {
        $out = [];
        foreach (explode("\n", $text) as $line) {
            if (str_contains($line, ':')) {
                [$name, $value] = explode(':', $line, 2);
                $out[strtolower(trim($name))] = trim($value);
            }
        }

        return $out;
    }

    /**
     * @param array<string, string> $headers
     */
    private static function headerText(array $headers): string
    {
        $names = ['project-id-version' => 'Project-Id-Version', 'language' => 'Language', 'mime-version' => 'MIME-Version', 'content-type' => 'Content-Type', 'content-transfer-encoding' => 'Content-Transfer-Encoding', 'plural-forms' => 'Plural-Forms', 'x-domain' => 'X-Domain'];
        $out = '';
        foreach ($names as $key => $name) {
            if (isset($headers[$key])) {
                $out .= $name . ': ' . $headers[$key] . "\n";
            }
        }

        return $out;
    }
}
