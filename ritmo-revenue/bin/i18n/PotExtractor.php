<?php

declare(strict_types=1);

namespace Ritmo\Tools\I18n;

use RecursiveDirectoryIterator;
use RecursiveIteratorIterator;

/**
 * The translatable texts of the plugin's PHP files, as a .pot file. A call counts when its
 * function is one of WordPress' translation functions, its texts are literal strings (joined
 * with "." if need be) and its text domain is the plugin's. A call of the plugin's domain whose
 * text is not literal cannot be extracted: it is reported as a warning.
 */
final class PotExtractor
{
    /** Function => positions of [singular, plural, context, domain] among its arguments (null: none). */
    private const FUNCTIONS = [
        '__' => [0, null, null, 1],
        '_e' => [0, null, null, 1],
        'esc_html__' => [0, null, null, 1],
        'esc_html_e' => [0, null, null, 1],
        'esc_attr__' => [0, null, null, 1],
        'esc_attr_e' => [0, null, null, 1],
        '_x' => [0, null, 1, 2],
        '_ex' => [0, null, 1, 2],
        'esc_html_x' => [0, null, 1, 2],
        'esc_attr_x' => [0, null, 1, 2],
        '_n' => [0, 1, null, 3],
        '_n_noop' => [0, 1, null, 2],
        '_nx' => [0, 1, 3, 4],
        '_nx_noop' => [0, 1, 2, 3],
    ];

    private const FOLDERS = ['src', 'templates'];

    private const FILES = ['ritmo-revenue.php', 'uninstall.php'];

    /** The one file allowed a __() with a text that is not literal (Admin\Components\DomainText). */
    private const DYNAMIC = 'src/Admin/Components/DomainText.php';

    private const SCHEMA_REF = 'src/Domain/Config/Schema.php';

    private const SCHEMA_COMMENT = 'translators: the name or the explanation of a setting of the rules';

    /** @var array<string, array{context: ?string, singular: string, plural: ?string, comments: list<string>, refs: list<string>}> */
    private array $entries = [];

    /** @var list<string> */
    private array $warnings = [];

    private bool $done = false;

    public function __construct(private readonly string $root, private readonly string $domain)
    {
    }

    public function pot(): string
    {
        $this->scan();
        $out = "# Ritmo Revenue: the texts of the plugin, for translators.\n"
            . "# This file is generated by bin/make-pot.php; do not edit it.\n"
            . "msgid \"\"\n"
            . "msgstr \"\"\n"
            . "\"Project-Id-Version: Ritmo Revenue\\n\"\n"
            . "\"MIME-Version: 1.0\\n\"\n"
            . "\"Content-Type: text/plain; charset=UTF-8\\n\"\n"
            . "\"Content-Transfer-Encoding: 8bit\\n\"\n"
            . "\"X-Domain: " . $this->domain . "\\n\"\n";
        foreach ($this->entries as $entry) {
            $out .= "\n";
            foreach ($entry['comments'] as $comment) {
                $out .= '#. ' . $comment . "\n";
            }
            $out .= '#: ' . implode(' ', $entry['refs']) . "\n";
            if ($entry['context'] !== null) {
                $out .= 'msgctxt ' . Po::quote($entry['context']) . "\n";
            }
            $out .= 'msgid ' . Po::quote($entry['singular']) . "\n";
            if ($entry['plural'] !== null) {
                $out .= 'msgid_plural ' . Po::quote($entry['plural']) . "\n";
                $out .= "msgstr[0] \"\"\nmsgstr[1] \"\"\n";
            } else {
                $out .= "msgstr \"\"\n";
            }
        }

        return $out;
    }

    public function count(): int
    {
        $this->scan();

        return count($this->entries);
    }

    /**
     * @return list<string>
     */
    public function warnings(): array
    {
        $this->scan();

        return $this->warnings;
    }

    /**
     * @return list<array{context: ?string, singular: string, plural: ?string}>
     */
    public function texts(): array
    {
        $this->scan();

        return array_values(array_map(static fn (array $e): array => ['context' => $e['context'], 'singular' => $e['singular'], 'plural' => $e['plural']], $this->entries));
    }

    private function scan(): void
    {
        if ($this->done) {
            return;
        }
        $this->done = true;
        foreach ($this->files() as $relative) {
            $this->file($relative);
        }
        foreach ($this->schemaTexts() as $text) {
            $this->add(null, $text, null, self::SCHEMA_REF, self::SCHEMA_COMMENT);
        }
    }

    /**
     * The labels and help texts of every setting of the rules (Domain\Config\Schema), which the
     * rules screen shows through Admin\Components\DomainText.
     *
     * @return list<string>
     */
    private function schemaTexts(): array
    {
        require_once $this->root . '/src/autoload.php';
        $out = [];
        foreach (\Ritmo\Domain\Config\Schema::ruleSet()->fields() as $field) {
            foreach ([$field->label, $field->help] as $text) {
                if ($text !== '') {
                    $out[$text] = true;
                }
            }
        }

        return array_keys($out);
    }

    /**
     * @return list<string> paths relative to the root, sorted
     */
    private function files(): array
    {
        $out = [];
        foreach (self::FOLDERS as $folder) {
            $it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($this->root . '/' . $folder, RecursiveDirectoryIterator::SKIP_DOTS));
            foreach ($it as $file) {
                if ($file->getExtension() === 'php') {
                    $out[] = substr($file->getPathname(), strlen($this->root) + 1);
                }
            }
        }
        foreach (self::FILES as $file) {
            if (is_file($this->root . '/' . $file)) {
                $out[] = $file;
            }
        }
        sort($out, SORT_STRING);

        return $out;
    }

    private function file(string $relative): void
    {
        $tokens = token_get_all((string) file_get_contents($this->root . '/' . $relative));
        $count = count($tokens);
        $comment = null;
        for ($i = 0; $i < $count; ++$i) {
            $token = $tokens[$i];
            if (is_array($token) && in_array($token[0], [T_COMMENT, T_DOC_COMMENT], true)) {
                if (stripos($token[1], 'translators:') !== false) {
                    $comment = ['text' => self::commentText($token[1]), 'line' => $token[2] + substr_count($token[1], "\n")];
                }
                continue;
            }
            if (!is_array($token) || $token[0] !== T_STRING || !isset(self::FUNCTIONS[$token[1]]) || self::isMethodOrDefinition($tokens, $i)) {
                continue;
            }
            $open = self::next($tokens, $i);
            if ($open === null || $tokens[$open] !== '(') {
                continue;
            }
            [$args, $end] = self::arguments($tokens, $open);
            $line = $token[2];
            $translators = $comment !== null && $line - $comment['line'] <= 2 ? $comment['text'] : null;
            $this->call($token[1], $args, $relative . ':' . $line, $translators);
            $comment = null;
            $i = $end;
        }
    }

    /**
     * @param list<string|null> $args each argument as a literal string, or null when it is not one
     */
    private function call(string $function, array $args, string $ref, ?string $translators): void
    {
        [$singularAt, $pluralAt, $contextAt, $domainAt] = self::FUNCTIONS[$function];
        if (($args[$domainAt] ?? null) !== $this->domain) {
            return;
        }
        $singular = $args[$singularAt] ?? null;
        $plural = $pluralAt === null ? null : ($args[$pluralAt] ?? null);
        $context = $contextAt === null ? null : ($args[$contextAt] ?? null);
        if ($singular === null || ($pluralAt !== null && $plural === null) || ($contextAt !== null && $context === null)) {
            if (!str_starts_with($ref, self::DYNAMIC . ':')) {
                $this->warnings[] = sprintf('%s: %s() with a text that is not literal cannot be translated.', $ref, $function);
            }

            return;
        }
        $this->add($context, $singular, $plural, $ref, $translators);
    }

    private function add(?string $context, string $singular, ?string $plural, string $ref, ?string $translators): void
    {
        $key = ($context ?? '') . "\4" . $singular;
        $this->entries[$key] ??= ['context' => $context, 'singular' => $singular, 'plural' => $plural, 'comments' => [], 'refs' => []];
        if ($translators !== null && !in_array($translators, $this->entries[$key]['comments'], true)) {
            $this->entries[$key]['comments'][] = $translators;
        }
        if (!in_array($ref, $this->entries[$key]['refs'], true)) {
            $this->entries[$key]['refs'][] = $ref;
        }
    }

    /**
     * @param list<mixed> $tokens
     *
     * @return array{0: list<string|null>, 1: int} the arguments and the position of the closing parenthesis
     */
    private static function arguments(array $tokens, int $open): array
    {
        $args = [];
        $parts = [];
        $literal = true;
        $depth = 0;
        $count = count($tokens);
        for ($i = $open + 1; $i < $count; ++$i) {
            $token = $tokens[$i];
            if ($token === '(' || $token === '[' || $token === '{') {
                ++$depth;
                $literal = false;
                continue;
            }
            if (($token === ')' || $token === ']' || $token === '}') && $depth > 0) {
                --$depth;
                continue;
            }
            if ($depth === 0 && ($token === ',' || $token === ')')) {
                $args[] = $literal && $parts !== [] ? implode('', $parts) : null;
                $parts = [];
                $literal = true;
                if ($token === ')') {
                    return [$args, $i];
                }
                continue;
            }
            if ($depth > 0 || (is_array($token) && in_array($token[0], [T_WHITESPACE, T_COMMENT, T_DOC_COMMENT], true)) || $token === '.') {
                continue;
            }
            if (is_array($token) && $token[0] === T_CONSTANT_ENCAPSED_STRING) {
                $parts[] = self::literal($token[1]);
                continue;
            }
            $literal = false;
        }

        return [$args, $count - 1];
    }

    /**
     * The value of a PHP string literal without variables.
     */
    private static function literal(string $code): string
    {
        $body = substr($code, 1, -1);
        if ($code[0] === "'") {
            return strtr($body, ['\\\\' => '\\', "\\'" => "'"]);
        }

        return (string) preg_replace_callback(
            '/\\\\(u\{[0-9A-Fa-f]+\}|x[0-9A-Fa-f]{1,2}|[0-7]{1,3}|.)/s',
            static function (array $m): string {
                $e = $m[1];

                return match (true) {
                    $e[0] === 'u' => mb_chr((int) hexdec(substr($e, 2, -1)), 'UTF-8'),
                    $e[0] === 'x' => chr((int) hexdec(substr($e, 1))),
                    ctype_digit($e) => chr((int) octdec($e)),
                    default => ['n' => "\n", 't' => "\t", 'r' => "\r", 'v' => "\v", 'e' => "\e", 'f' => "\f", '\\' => '\\', '$' => '$', '"' => '"'][$e] ?? '\\' . $e,
                };
            },
            $body
        );
    }

    /**
     * @param list<mixed> $tokens
     */
    private static function next(array $tokens, int $i): ?int
    {
        $count = count($tokens);
        for ($j = $i + 1; $j < $count; ++$j) {
            if (!is_array($tokens[$j]) || $tokens[$j][0] !== T_WHITESPACE) {
                return $j;
            }
        }

        return null;
    }

    /**
     * A method call ($x->__()), a static call (X::__()) or a function definition is not a call of
     * the WordPress function.
     *
     * @param list<mixed> $tokens
     */
    private static function isMethodOrDefinition(array $tokens, int $i): bool
    {
        for ($j = $i - 1; $j >= 0; --$j) {
            $t = $tokens[$j];
            if (is_array($t) && $t[0] === T_WHITESPACE) {
                continue;
            }

            return is_array($t) && in_array($t[0], [T_OBJECT_OPERATOR, T_NULLSAFE_OBJECT_OPERATOR, T_DOUBLE_COLON, T_FUNCTION], true);
        }

        return false;
    }

    private static function commentText(string $comment): string
    {
        $text = preg_replace('#^/\*+|\*+/$|^//#', '', trim($comment));
        $text = preg_replace('/^\s*\*\s?/m', '', (string) $text);
        $text = trim((string) preg_replace('/\s+/', ' ', (string) $text));
        $at = stripos($text, 'translators:');

        return $at === false ? $text : substr($text, $at);
    }
}
