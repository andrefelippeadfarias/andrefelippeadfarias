/**
 * Parity of the confirmation, delivery and wave functions with the reference engine
 * (tests/fixtures/golden/m3/verify, generated by tests/fixtures/tools/golden_verify.py): amounts
 * within 0.01, counts and verdicts exact. The raw formats of the reference (its calendar rows,
 * listing directory and booking rows) are mapped here the way the connectors map them.
 */
final class VerifyGoldenTest extends TestCase
{
    private const DIR = 'golden/m3/verify/';

    #[DataProvider('liveness')]
    public function testRuleLiveness(array $in, array $expected): void
    {
        $item = $in['item'];
        $recalc = $in['recalc_night'];
        $issue = RuleLiveness::check(
            in_array($item['price_type'] ?? null, ['fixed', 'percent'], true),
            isset($item['min_price']) ? (float) $item['min_price'] : null,
            (string) ($recalc['dso_flag'] ?? '') === '1',
            isset($recalc['min_price']) ? (float) $recalc['min_price'] : null,
        );

        self::assertSame($expected['inactive'], $issue !== null);
        self::assertSame($expected['kind'], $issue?->value ?? '');
    }

    #[DataProvider('slack')]
    public function testPercentSlack(array $in, float|int $expected): void
    {
        self::assertEqualsWithDelta((float) $expected, PercentSlack::of((float) $in['value'], (float) $in['base']), 1e-6);
    }

    #[DataProvider('isolated')]
    public function testIsolatedNight(array $in, bool $expected): void
    {
        $calendar = [];
        foreach ($in['calendar'] as $date => $row) {
            [$sold, $total] = self::soldTotal($row, (int) $in['units']);
            $calendar[$date] = new PriceNight(Days::date($date), 100.0, null, null, null, $sold, $total);
        }

        self::assertSame($expected, IsolatedNight::is($calendar, Days::date($in['night'])));
    }

    #[DataProvider('pushes')]
    public function testPushTimes(array $in, array $expected): void
    {
        $collect = $in['collect']['result'] ?? $in['collect'];
        $listings = array_map(static fn (array $s): ListingInfo => new ListingInfo(
            (string) $s['listing_id'],
            'listing',
            null,
            null,
            null,
            null,
            new SyncStatus(($s['push_enabled'] ?? true) !== false, PushTimes::parseInstant($s['last_date_pushed'] ?? null)),
        ), $collect['contexto']['sync']);
        $times = PushTimes::fromListings($in['listing_room'], $listings);

        self::assertSame($expected['pushed_at'], array_map(static fn (DateTimeImmutable $t): string => $t->format('Y-m-d\TH:i:s\Z'), $times->pushedAt));
        self::assertCount($expected['left_out'], $times->leftOut);
    }

    #[DataProvider('reread')]
    public function testPmsCalendarCheck(array $in, array $expected): void
    {
        $writes = array_map(static fn (array $i): PmsWrite => new PmsWrite(
            $i['quarto'],
            Days::date($i['de']),
            Days::date($i['ate']),
            self::pmsFields($i['min_stay'] ?? null, $i['max_stay'] ?? null, $i['override'] ?? null, $i['num_avail'] ?? null, $i['canais_max'] ?? []),
            $i['num_avail_esperado'] ?? null,
        ), $in['items']);
        $reread = [];
        foreach ($in['reread'] as $room => $nights) {
            foreach ($nights as $date => $v) {
                $reread[$room][$date] = self::pmsFields($v['minStay'] ?? null, $v['maxStay'] ?? null, $v['override'] ?? null, $v['numAvail'] ?? null, $v['canais_max'] ?? []);
            }
        }
        $result = PmsCalendarCheck::compare($writes, $reread);

        self::assertCount($expected['errors'], $result->differences);
        self::assertSame($expected['items_with_error'], $result->writesWithError);
    }

    #[DataProvider('waves')]
    public function testCancellationWaves(array $in, array $expected): void
    {
        $bookings = array_map(static fn (array $b): BookingRecord => new BookingRecord(
            (string) $b['id'],
            'R' . $b['roomId'],
            Days::date('2026-12-01'),
            Days::date('2026-12-03'),
            $b['status'] === 'cancelled' ? BookingStatus::Cancelled : BookingStatus::Confirmed,
            (string) $b['channel'],
            (string) $b['referer'],
            (float) $b['price'],
            self::instant($b['bookingTime']),
            self::instant($b['modifiedTime']),
            self::instant($b['cancelTime']),
        ), $in['bookings']);
        $waves = (new CancellationWave(new WaveConfig($in['min_count'], $in['window_hours'])))->detect($bookings, self::instant($in['since']));

        self::assertSame(
            array_map(static fn (array $w): array => ['channel' => $w['channel'], 'bookings' => array_map('strval', $w['bookings'])], $expected),
            array_map(static fn (Wave $w): array => ['channel' => $w->channel, 'bookings' => $w->bookingRefs], $waves),
        );
    }

    /**
     * With the PMS price at the step's value, a step reaches the channel exactly when the
     * reference's marcar_envio marks it (M2 golden): the push rule is the same, the PMS price is
     * the plugin's extra condition (divergence C3).
     */
    #[DataProvider('marks')]
    public function testChannelArrivalMarksAsThePushRule(array $in, array $expected): void
    {
        $records = Reference::ledger($in['ledger'])->records();
        $rooms = array_unique(array_map(static fn ($r): string => $r->roomCode, $records));
        $pushed = is_array($in['pushed_until'])
            ? array_map([self::class, 'instant'], $in['pushed_until'])
            : array_fill_keys($rooms, self::instant($in['pushed_until']));
        $prices = [];
        foreach ($records as $r) {
            $prices[$r->roomCode . '|' . Days::key($r->night)] = $r->priceTo;
        }
        $report = (new ChannelArrival())->check($records, $pushed, $prices, array_fill_keys($rooms, 100.0), self::instant('2027-03-08T16:00:00Z'));

        $marked = [];
        foreach ($expected['ledger'] as $i => $row) {
            if (($in['ledger'][$i]['chegou_ao_canal'] ?? false) === false && $row['chegou_ao_canal'] !== false) {
                $marked[] = $i;
            }
        }
        self::assertSame($marked, array_keys($report->delivered));
        self::assertCount($expected['marked'], $report->delivered);
    }

    public static function liveness(): iterable
    {
        return self::provider('ler_recalculo.regra_inativa');
    }

    public static function slack(): iterable
    {
        return self::provider('ler_recalculo.tolerancia_percentual');
    }

    public static function isolated(): iterable
    {
        return self::provider('ler_recalculo.dia_isolado');
    }

    public static function pushes(): iterable
    {
        return self::provider('pace.envios_da_coleta');
    }

    public static function reread(): iterable
    {
        return self::provider('beds24._conferir');
    }

    public static function waves(): iterable
    {
        return self::provider('vigia_seguranca.classificar.waves');
    }

    public static function marks(): iterable
    {
        return Reference::provider('pace.marcar_envio');
    }

    public function testTheManifestCountsEveryFile(): void
    {
        $manifest = Fixtures::json(self::DIR . 'MANIFEST.json');

        self::assertFalse($manifest['engine_dirty']);
        foreach ($manifest['files'] as $file => $count) {
            self::assertCount($count, Fixtures::json(self::DIR . $file)['cases'], $file);
        }
        self::assertSame(37, array_sum($manifest['files']));
    }

    /**
     * @return iterable<string, array{0: array<string, mixed>, 1: mixed}>
     */
    private static function provider(string $function): iterable
    {
        foreach (Fixtures::json(self::DIR . $function . '.json')['cases'] as $case) {
            yield $case['name'] => [$case['input'], $case['expected']];
        }
    }

    /**
     * The reference's comum.vendidas_total: "sold/total" (or the collect's field), else the
     * bookings of a single-unit room.
     *
     * @param array<string, mixed> $row
     *
     * @return array{0: int, 1: int}
     */
    private static function soldTotal(array $row, int $units): array
    {
        $mu = (string) ($row['mu_occupancy'] ?? $row['multi_unit_occupancy'] ?? '');
        if (str_contains($mu, '/')) {
            [$sold, $total] = explode('/', $mu, 2);

            return [(int) $sold, (int) $total];
        }

        return [min((int) ($row['num_bookings'] ?? 0), $units), $units];
    }

    /**
     * @param array<string, string|null> $channels
     */
    private static function pmsFields(?int $minStay, ?int $maxStay, ?string $override, ?int $available, array $channels): NightFields
    {
        $fields = [
            ChangeField::PMS_MIN_STAY => $minStay,
            ChangeField::PMS_MAX_STAY => $maxStay,
            ChangeField::PMS_RESTRICTION => $override,
            ChangeField::PMS_AVAILABLE => $available,
        ];
        foreach ($channels as $channel => $limit) {
            $fields[ChangeField::channelLimit($channel)] = $limit;
        }

        return new NightFields($fields);
    }

    private static function instant(string $text): DateTimeImmutable
    {
        return (new DateTimeImmutable($text, new DateTimeZone('UTC')))->setTimezone(new DateTimeZone('UTC'));
    }
}
